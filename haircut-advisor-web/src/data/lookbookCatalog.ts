// Fallback generator when shape is round, oblong, heart, or diamond
export function getLookbookForShape(
  shape: string,
  clientPhoto: string | null
): GeneratedClientHaircut[] {
  const normalizedShape = shape.toLowerCase();
  const templateList =
    LOOKBOOK_TEMPLATES_BY_SHAPE[normalizedShape] || LOOKBOOK_TEMPLATES_BY_SHAPE.square;

  return templateList.map((tpl, idx) => {
    // If clientPhoto is provided, use it directly as the base image for this haircut option
    // so no stock photos of other people are ever shown!
    let imgUrl = clientPhoto;
    if (!imgUrl) {
      // Elegant dark barber card placeholder if photo not yet taken
      imgUrl = `data:image/svg+xml;utf8,<svg xmlns="http://www.w3.org/2000/svg" width="600" height="800" viewBox="0 0 600 800"><rect width="100%" height="100%" fill="%230e121a"/><circle cx="300" cy="380" r="170" fill="%23e5b869" opacity="0.18"/><path d="M190,260 Q300,190 410,250 Q380,300 300,285 Q220,300 190,260 Z" fill="%231e2430"/><text x="300" y="730" font-family="sans-serif" font-size="22" fill="%23e5b869" font-weight="bold" text-anchor="middle">${encodeURIComponent(tpl.name)}</text></svg>`;
    }

    return {
      ...tpl,
      generated_image_url: imgUrl,
      match_percentage: tpl.match_percentage || (95 - idx * 2),
    };
  });
}
